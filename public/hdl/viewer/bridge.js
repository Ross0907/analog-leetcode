import './viewer-shell.js';
let running = false;
let pending = null;
const shortcuts = document.getElementById('shortcuts');
const shortcutsOpen = document.getElementById('shortcuts-open');
const shortcutsContent = document.getElementById('shortcuts-content');
function closeShortcuts() {
  shortcuts.close();
  shortcutsOpen.focus();
}
function openShortcuts() {
  const nativeHelp = document.querySelector('#waveform .wd-help-panel');
  if (!nativeHelp?.firstElementChild) return;
  // Use the shortcut table generated by this exact upstream runtime version.
  shortcutsContent.replaceChildren(nativeHelp.firstElementChild.cloneNode(true));
  for(const row of shortcutsContent.querySelectorAll('.wd-help-panel-row'))if(row.textContent.includes('Toggle edit mode'))row.remove();
  if (!shortcuts.open) shortcuts.showModal();
}
shortcutsOpen.addEventListener('click', openShortcuts);
document.getElementById('shortcuts-close').addEventListener('click', closeShortcuts);
shortcuts.addEventListener('cancel', event => { event.preventDefault(); closeShortcuts(); });
shortcuts.addEventListener('click', event => {
  if (event.target !== shortcuts) return;
  const bounds = shortcuts.getBoundingClientRect();
  if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) closeShortcuts();
});
const helpObserver = new MutationObserver(() => {
  shortcutsOpen.disabled = !document.querySelector('#waveform .wd-help-panel > *');
});
helpObserver.observe(document.getElementById('waveform'), { childList:true, subtree:true });
window.addEventListener('keydown', event => {
  if (event.isComposing) return;
  if ((event.ctrlKey || event.metaKey) && event.key === 'Enter') {
    event.preventDefault(); event.stopImmediatePropagation();
    if (!event.repeat) window.parent.postMessage({type:'anacode-hdl-shortcut',action:event.shiftKey?'submit':'run'}, location.origin);
  } else if (event.key === '?' && !event.ctrlKey && !event.metaKey && !event.altKey && !(event.target instanceof Element && event.target.closest('input,textarea,[contenteditable=true]'))) {
    event.preventDefault(); event.stopImmediatePropagation();
    if (shortcuts.open) closeShortcuts(); else openShortcuts();
  }
}, true);
function showError() {
  const error = document.getElementById('error');
  error.hidden = false;
  error.textContent = 'This VCD could not be displayed. Download it to inspect in GTKWave.';
}
// The upstream file importer is async; DOM event dispatch cannot await it.
window.addEventListener('unhandledrejection', showError);
window.addEventListener('error', showError);
async function display(vcd) {
  if (running) { pending = vcd; return; }
  running = true;
  try {
    // v1.6 exposes its file-open control, not the later trunk URL argument.
    // Use that upstream importer so VCD parsing and rendering remain VCDrom's.
    await window.VCDrom('waveform');
    const input = document.getElementById('inputfile');
    if (!input) throw new Error('VCDrom file input is missing');
    const transfer = new DataTransfer();
    transfer.items.add(new File([vcd], 'dump.vcd', { type: 'text/plain' }));
    input.files = transfer.files;
    input.dispatchEvent(new Event('change', { bubbles: true }));
    document.getElementById('error').hidden = true;
  } catch {
    showError();
  } finally {
    running = false;
    if (pending !== null) { const next = pending; pending = null; void display(next); }
  }
}
window.addEventListener('message', event => {
  if(event.source !== window.parent || event.origin !== location.origin) return;
  if(event.data?.type==='anacode-viewer-theme'&&['light','dark'].includes(event.data.theme)){document.documentElement.dataset.theme=event.data.theme;return;}
  if(event.data?.type !== 'anacode-vcd' || typeof event.data.vcd !== 'string' || event.data.vcd.length > 8*1024*1024) return;
  void display(event.data.vcd);
});
document.documentElement.dataset.theme=window.matchMedia('(prefers-color-scheme: dark)').matches?'dark':'light';
window.parent.postMessage({ type: 'anacode-viewer-ready' }, location.origin);
