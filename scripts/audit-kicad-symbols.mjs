import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { resolve, relative, join, basename } from "node:path";

const root = resolve(process.argv[2] ?? "public/kicad");
const manifest = JSON.parse(readFileSync(join(root, "symbols.json"), "utf8"));
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const read = (path) => {
  const absolute = resolve(root, path);
  assert(!relative(root, absolute).startsWith(".."), "KiCad artifact escaped its directory");
  return readFileSync(absolute);
};
assert.equal(manifest.schemaVersion, 1);
assert.equal(manifest.kicadVersion, "9.0.9");
assert.equal(manifest.libraryRevision, "ad36cd14bcd1b1cd0484f629ccdd3481366f74f3");
assert.equal(manifest.generator, "official kicad-cli sym export svg");
assert.equal(manifest.license, "CC-BY-SA-4.0 with KiCad library exception");
for (const [file, expected] of Object.entries(manifest.sourceHashes)) {
  assert.equal(sha256(read(`source/${file}`)), expected, `Official KiCad input changed: ${file}`);
}
assert.equal(sha256(read("LICENSE.md")), manifest.sourceHashes["LICENSE.md"]);
assert(read("README.md").toString().includes("KiCad community"), "Missing KiCad community attribution");
const notice = read("NOTICE.html").toString();
assert(notice.includes("KiCad community") && notice.includes(manifest.libraryRevision), "Missing public KiCad source attribution");
assert(notice.includes('href="LICENSE.md"') && notice.includes("LM2904 device model"), "Missing public license or model clarification");

const number = "[-+]?(?:\\d*\\.\\d+|\\d+\\.?\\d*)(?:[eE][-+]?\\d+)?";
let totalPins = 0;
for (const [id, symbol] of Object.entries(manifest.symbols)) {
  assert.equal(symbol.sourceId, id);
  assert.equal(symbol.unit, 1);
  assert(symbol.svg.startsWith("/kicad/svg/") && symbol.stockSvg.startsWith("/kicad/stock/"));
  const svg = read(symbol.svg.slice("/kicad/".length));
  const stock = read(symbol.stockSvg.slice("/kicad/".length));
  assert.equal(sha256(svg), symbol.sha256, `Modified KiCad SVG: ${id}`);
  assert.equal(sha256(stock), symbol.stockSha256, `Modified stock KiCad SVG: ${id}`);
  assert.equal(symbol.sourceSha256, manifest.sourceHashes[basename(symbol.sourceFile)]);
  for (const link of [symbol.svg, symbol.stockSvg, symbol.sourceFile]) {
    assert(notice.includes(`href="${link}"`), `Public KiCad credits omit ${link}`);
  }
  const text = svg.toString();
  assert(text.includes("Image generated by Eeschema-SVG"), `${id} lacks native KiCad exporter metadata`);
  assert(!/<(?:script|foreignObject)\b/i.test(text), `${id} contains unexpected executable SVG content`);
  const actualViewBox = text.match(/\bviewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  assert.deepEqual(symbol.viewBox, actualViewBox, `${id} viewBox differs from artwork`);
  assert(symbol.viewBox.every(Number.isFinite) && symbol.origin.every(Number.isFinite));
  assert(Number.isFinite(symbol.unitsPerMm) && symbol.unitsPerMm > 0);
  const points = [...text.matchAll(new RegExp(`[ML]\\s*(${number})[\\s,]+(${number})`, "g"))]
    .map((match) => [Number(match[1]), Number(match[2])]);
  for (const pin of symbol.pins) {
    totalPins += 1;
    assert([pin.x, pin.y, pin.bodyX, pin.bodyY, pin.sourceX, pin.sourceY, pin.length, pin.angle].every(Number.isFinite));
    assert(Math.abs(pin.x - (symbol.origin[0] + pin.sourceX * symbol.unitsPerMm)) < 0.00001);
    assert(Math.abs(pin.y - (symbol.origin[1] - pin.sourceY * symbol.unitsPerMm)) < 0.00001);
    assert(points.some(([x, y]) => Math.hypot(x - pin.x, y - pin.y) <= 0.002 * symbol.unitsPerMm),
      `${id} pin ${pin.number} is disconnected from native exported artwork`);
    assert(Math.abs(Math.hypot(pin.bodyX - pin.x, pin.bodyY - pin.y) - pin.length * symbol.unitsPerMm) < 0.00001);
  }
}
for (const [id, names] of Object.entries({
  "Device:Q_NMOS": ["G", "D", "S"],
  "Device:Q_PMOS": ["G", "D", "S"],
  "Amplifier_Operational:LM2904": ["+", "-", "~"],
})) {
  assert.deepEqual(manifest.symbols[id].pins.map((pin) => pin.name), names, `${id} terminal contract changed`);
}
for (const [directory, key] of [["svg", "svg"], ["stock", "stockSvg"]]) {
  assert.deepEqual(readdirSync(join(root, directory)).sort(), Object.values(manifest.symbols).map((symbol) => basename(symbol[key])).sort());
}
console.log(`KiCad ${manifest.kicadVersion}: ${Object.keys(manifest.symbols).length} official SVG pairs and ${totalPins} pin anchors verified.`);
